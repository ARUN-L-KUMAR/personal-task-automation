class SendEmailRequest(BaseModel):
    to: str
    subject: str
    body: str


@router.post("/send")
def send_new_email(
    to: str = Query(..., description="Recipient"),
    subject: str = Query(..., description="Subject"),
    body: str = Query(..., description="Body"),
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Send an email from the current user's Gmail account."""
    if not is_authenticated(current_user, db):
        raise HTTPException(status_code=401, detail="Google not connected. Please connect Google account in Settings.")
    
    try:
        result = send_email(current_user, db, to=to, subject=subject, body=body)
        return {"status": "success", "result": result}
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


@router.post("/ai-reply-draft")
def generate_ai_reply_draft(
    message_id: str = Query(..., description="Message ID to draft a reply for"),
    tone: str = Query("professional", description="Reply tone: professional, friendly, formal, brief"),
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Generate an AI email reply draft from an existing Gmail message."""
    if not is_authenticated(current_user, db):
        raise HTTPException(status_code=401, detail="Google not connected. Please connect Google account in Settings.")

    try:
        message = get_message(current_user, db, message_id)

        sender_raw = message.get("from", "")
        sender_name, sender_email = parseaddr(sender_raw)
        reply_to = sender_email or sender_raw

        original_subject = (message.get("subject") or "").strip()
        if original_subject.lower().startswith("re:"):
            reply_subject = original_subject
        else:
            reply_subject = f"Re: {original_subject}" if original_subject else "Re:"

        source_text = ((message.get("body") or "").strip() or (message.get("snippet") or "").strip())
        if not source_text:
            raise HTTPException(status_code=400, detail="Email body is empty. Cannot generate a draft reply.")

        safe_tone = (tone or "professional").strip().lower()
        allowed_tones = {"professional", "friendly", "formal", "brief"}
        if safe_tone not in allowed_tones:
            safe_tone = "professional"

        system_prompt = (
            "You are an assistant that writes polished email replies. "
            "Return only the email body text, ready to send. "
            "Do not include markdown, subject lines, or explanatory notes."
        )

        user_prompt = f"""
Write a {safe_tone} email reply to the message below.

Sender Name: {sender_name or 'Unknown'}
Sender Address: {reply_to}
Original Subject: {original_subject or '(No Subject)'}

Original Message:
{source_text[:5000]}

Requirements:
- Keep it concise (about 4 to 8 sentences).
- Acknowledge the main point of the sender.
- Include a clear next step or confirmation.
- Keep the tone respectful and natural.
""".strip()

        draft_body, model_used = _invoke_with_fallback([
            ("system", system_prompt),
            ("human", user_prompt),
        ])

        return {
            "status": "success",
            "to": reply_to,
            "subject": reply_subject,
            "draft_body": draft_body,
            "model": model_used,
            "message_id": message_id,
        }

    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
