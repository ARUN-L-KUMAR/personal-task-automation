"""
Gmail API Router (Multi-User Version)

Endpoints:
- GET  /api/email/inbox  → Fetch recent emails (for current user)
- GET  /api/email/{id}   → Get email details
- POST /api/email/send   → Send an email
"""

from fastapi import APIRouter, HTTPException, Query, Depends
from pydantic import BaseModel
from typing import Optional, List, Tuple
import os
from email.utils import parseaddr
from sqlalchemy.orm import Session

from utils.google_auth import is_authenticated
from utils.google_gmail import get_inbox, get_message, send_email
from database.connection import get_db
from database.models import User
from middleware import get_current_user

router = APIRouter(prefix="/email", tags=["Email"])


def _build_llm_fallback_chain() -> List[Tuple[str, object]]:
    """Build a fallback chain that mirrors chatbot model ordering."""
    from config.settings import (
        llm,
        llm_gemini_25_flash,
        llm_gemini_25_lite,
        llm_openrouter,
        llm_openrouter_alt,
        llm_openrouter_alt2,
    )

    has_google = bool(os.getenv("GOOGLE_API_KEY"))
    has_openrouter = bool(os.getenv("OPENROUTER_API_KEY"))

    models: List[Tuple[str, object]] = [("groq-primary", llm)]
    if has_google:
        models.append(("gemini-2.5-flash-lite", llm_gemini_25_lite))
    if has_openrouter:
        models.append(("openrouter-nemotron-30b", llm_openrouter))
    if has_google:
        models.append(("gemini-2.5-flash", llm_gemini_25_flash))
    if has_openrouter:
        models.append(("openrouter-trinity-large", llm_openrouter_alt))
        models.append(("openrouter-solar-pro", llm_openrouter_alt2))

    return models


def _is_retryable_llm_error(error_text: str) -> bool:
    lowered = error_text.lower()
    return (
        "429" in lowered
        or "402" in lowered
        or "503" in lowered
        or "500" in lowered
        or "rate" in lowered
        or "overloaded" in lowered
        or "spend limit" in lowered
        or "balance" in lowered
    )


def _invoke_with_fallback(messages: List[tuple]) -> Tuple[str, str]:
    """Invoke available models in order until one returns a usable draft."""
    fallback_models = _build_llm_fallback_chain()
    if not fallback_models:
        raise HTTPException(status_code=502, detail="No AI model is configured for drafting replies.")

    last_error = ""
    for idx, (label, active_llm) in enumerate(fallback_models):
        try:
            response_msg = active_llm.invoke(messages)
            content = getattr(response_msg, "content", "")
            draft_text = str(content).strip()
            if not draft_text:
                raise Exception("Empty draft generated by model")
            return draft_text, label
        except Exception as exc:
            last_error = str(exc)
            if _is_retryable_llm_error(last_error) and idx < len(fallback_models) - 1:
                continue

    raise HTTPException(
        status_code=502,
        detail=f"Unable to generate AI reply draft right now. Last error: {last_error[:180]}"
    )


@router.get("/inbox")
def fetch_inbox(
    max_results: int = Query(50, description="Number of emails"),
    query: Optional[str] = Query("", description="Gmail search query"),
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Fetch recent inbox emails for the current user."""
    if not is_authenticated(current_user, db):
        raise HTTPException(status_code=401, detail="Google not connected. Please connect Google account in Settings.")
    
    try:
        emails = get_inbox(current_user, db, max_results=max_results, query=query)
        return {"status": "success", "emails": emails, "count": len(emails)}
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


